export function getCityBySlug(slug: string): GeoCity | undefined {
  return GEO_CITIES.find((c) => c.slug === slug);
}

export function getHubBySlug(slug: string): GeoHub | undefined {
  return GEO_HUBS.find((h) => h.slug === slug);
}

export function getCitiesByDirection(direction: GeoDirection): GeoCity[] {
  return GEO_CITIES.filter((c) => c.direction === direction);
}

export function getHubByDirection(direction: GeoDirection): GeoHub {
  const hub = GEO_HUBS.find((h) => h.direction === direction);
  if (!hub) {
    throw new Error(`Hub for direction ${direction} not found`);
  }
  return hub;
}

export function getNeighbourCities(city: GeoCity, limit = 6): GeoCity[] {
  const sameDirection = GEO_CITIES.filter(
    (c) => c.direction === city.direction && c.slug !== city.slug
  );
  const byDistance = [...sameDirection].sort(
    (a, b) => Math.abs(a.distanceKm - city.distanceKm) - Math.abs(b.distanceKm - city.distanceKm)
  );
  return byDistance.slice(0, limit);
}

export function getWave1Cities(): GeoCity[] {
  return GEO_CITIES.filter((c) => c.wave === 1);
}

export const GEO_SLUGS: string[] = GEO_CITIES.map((c) => c.slug);
export const GEO_HUB_SLUGS: string[] = GEO_HUBS.map((h) => h.slug);
