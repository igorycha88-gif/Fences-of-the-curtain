async function main() {
  console.log('Seeding service pages...');

  for (const pageData of servicePages) {
    const existing = await prisma.pageContent.findUnique({
      where: { slug: pageData.slug },
    });

    if (existing) {
      console.log(`  [SKIP] ${pageData.slug} already exists`);
      continue;
    }

    await prisma.pageContent.create({ data: pageData });
    console.log(`  [OK] ${pageData.slug}`);
  }

  console.log('Done!');
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
