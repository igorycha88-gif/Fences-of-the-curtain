export async function seedSeoBlogPosts(): Promise<{ created: number; updated: number; skipped: number }> {
  let created = 0;
  let updated = 0;
  let skipped = 0;

  for (const post of POSTS) {
    const existing = await prisma.blogPost.findUnique({ where: { slug: post.slug }, select: { id: true, updatedAt: true } });

    if (existing) {
      await prisma.blogPost.update({
        where: { slug: post.slug },
        data: {
          title: post.title,
          excerpt: post.excerpt,
          content: post.content as unknown as object,
          seoTitle: post.seoTitle,
          seoDescription: post.seoDescription,
          seoKeywords: post.seoKeywords,
          published: true,
        },
      });
      updated += 1;
      console.log(`[UPDATED] blogPost ${post.slug}`);
      continue;
    }

    await prisma.blogPost.create({
      data: {
        title: post.title,
        slug: post.slug,
        excerpt: post.excerpt,
        content: post.content as unknown as object,
        seoTitle: post.seoTitle,
        seoDescription: post.seoDescription,
        seoKeywords: post.seoKeywords,
        coverImage: post.coverImage,
        published: true,
      },
    });
    created += 1;
    console.log(`[CREATED] blogPost ${post.slug}`);
  }

  skipped = POSTS.length - created - updated;
  return { created, updated, skipped };
}
